#!/usr/bin/env python3
"""Write guides/getting-started/code-examples.mdx from the type-checked files in examples/.

    python3 scripts/sync-examples-page.py           # rewrite the page
    python3 scripts/sync-examples-page.py --check   # fail when the page is out of date (CI)

Edit the example files, never the page. examples/ is not published, so the page is how readers see them.
"""
import argparse
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
PAGE = ROOT / "guides/getting-started/code-examples.mdx"
SOURCE = "https://github.com/nozle-dev/NozleDocs/blob/main/examples"

# title, what it shows, Node file, Python file, related pages
SCENARIOS = [
    (
        "Track usage",
        "Record a billable event with a stable transaction ID, and spend credits for one unit of work in a single call.",
        "track-usage.ts",
        "track_usage.py",
        [("Node.js events", "/sdks/node/tracking-events"), ("Python events", "/sdks/python/tracking-events"), ("Atomic usage tracking", "/sdks/node/credits#atomic-usage-tracking")],
    ),
    (
        "Check an entitlement",
        "Gate a request with `can()`: deny only when `allowed` is false, and treat `overage` as billed, not refused.",
        "check-entitlement.ts",
        "check_entitlement.py",
        [("Node.js entitlements", "/sdks/node/entitlements"), ("Python entitlements", "/sdks/python/entitlements"), ("Entitlements", "/guides/entitlements/overview")],
    ),
    (
        "Create a checkout and handle the result",
        "Start a checkout from your backend and handle every result type: `hosted`, `razorpay`, `processing`, `completed` and `scheduled`.",
        "checkout.ts",
        "checkout.py",
        [("Checkout", "/guides/billing/checkout"), ("Node.js billing", "/sdks/node/billing#create-checkout"), ("Python billing", "/sdks/python/billing")],
    ),
    (
        "Verify and handle a webhook",
        "Verify the Standard Webhooks signature on the raw body, skip duplicate deliveries, and act on subscription and invoice events.",
        "webhooks.ts",
        "webhooks.py",
        [("Receive Nozle webhooks", "/api/receive-webhooks"), ("Webhook events", "/api/webhook-events")],
    ),
    (
        "Read a credit balance",
        "Show the available and held credits, the sources that expire, and recent credit operations.",
        "credit-balance.ts",
        "credit_balance.py",
        [("Node.js credits", "/sdks/node/credits"), ("Python credits", "/sdks/python/credits")],
    ),
    (
        "Change or cancel a subscription",
        "Preview a plan change, apply the confirmed quote (an upgrade through checkout, a downgrade as a transition), cancel at period end, keep, or cancel now.",
        "change-subscription.ts",
        "change_subscription.py",
        [("Node.js subscription self-service", "/sdks/node/billing#subscription-self-service"), ("Plan transition policies", "/api/plan-transition-policies")],
    ),
]


def code(name: str, language: str) -> str:
    text = (ROOT / "examples" / name).read_text().rstrip("\n")
    assert "```" not in text, f"{name} contains a code fence"
    return f"```{language} {name}\n{text}\n```"


def render() -> str:
    lines = [
        "---",
        'title: "Code examples"',
        'description: "Server-side Node.js and Python examples for the common Nozle tasks: usage, entitlements, checkout, webhooks, credits and plan changes."',
        'keywords: ["examples", "sample code", "track usage", "can", "checkout", "webhooks", "credits", "cancel subscription"]',
        "---",
        "",
        "{/* Generated by scripts/sync-examples-page.py from examples/. Edit the example files, not this page. */}",
        "",
        "Each example is compiled against the current `@nozle-js/node` and type-checked against the current `nozle-sdk` in documentation CI, "
        "so the calls and fields match the published SDKs. They run on your server with a secret key from `NOZLE_SECRET_KEY`; "
        "never send a secret key to a browser. Replace plan, feature and credit system codes with your own.",
        "",
    ]
    for title, summary, ts, py, related in SCENARIOS:
        links = ", ".join(f"[{label}]({href})" for label, href in related)
        lines += [
            f"## {title}",
            "",
            summary,
            "",
            "<CodeGroup>",
            "",
            code(ts, "ts"),
            "",
            code(py, "python"),
            "",
            "</CodeGroup>",
            "",
            f"Source: [{ts}]({SOURCE}/{ts}), [{py}]({SOURCE}/{py}). See also {links}.",
            "",
        ]
    lines += [
        "## React checkout",
        "",
        f"[`merchant-backend-checkout.tsx`]({SOURCE}/merchant-backend-checkout.tsx) starts checkout from an authenticated backend route for the React `PricingTable`. "
        f"[`stripe-checkout.tsx`]({SOURCE}/stripe-checkout.tsx) and [`razorpay-checkout.tsx`]({SOURCE}/razorpay-checkout.tsx) show the provider flows. "
        "See [React components](/sdks/react/components).",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="exit 1 when the page differs from the examples")
    args = parser.parse_args()
    page = render()
    if args.check:
        if not PAGE.exists() or PAGE.read_text() != page:
            sys.exit(f"{PAGE.relative_to(ROOT)} is out of date: run python3 scripts/sync-examples-page.py")
        return
    PAGE.write_text(page)
    print(f"wrote {PAGE.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
